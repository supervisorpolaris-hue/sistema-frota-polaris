process.env.TZ = 'America/Sao_Paulo';
const assert = require('assert');
const { makeEnv, load } = require('./gasmock'); const { build } = require('./data');
const FILE = process.argv[2]; const ok = m => console.log('✓', m);
const tmp = makeEnv({ sheets: {}, props: {} }); load(tmp, FILE);
const DATA = build({ schema: JSON.parse(JSON.stringify(tmp.ctx.SCHEMA)) });
const env = makeEnv(DATA);
const exec = (fn, ...a) => { load(env, FILE); const r = env.ctx[fn](...a); return r == null ? r : JSON.parse(JSON.stringify(r)); };
const F = { data: 'eA==', mime: 'image/jpeg' };
const saida = x => Object.assign({ data: '2026-11-17', moto: 'MOTO 04', entregador: 'Ana Paula Souza', turno: '18h-00h', kmIni: 88000, checklist: {}, forcar: true }, x);
assert.strictEqual(exec('getApp').config.fotoObrigatoria, true);
assert.throws(() => exec('openShift', saida()), /Tire a foto do painel com o KM de saída/);
assert(exec('openShift', saida({ fotoIni: F })).ok);
ok('saída sem foto é recusada; com foto, grava');
const aberto = exec('getApp').openShifts.find(o => o.kmIni === 88000);
assert.throws(() => exec('closeShift', aberto.row, { moto: 'MOTO 04', kmFim: 88100, corridas: 10 }), /KM de retorno/);
assert(exec('closeShift', aberto.row, { moto: 'MOTO 04', kmFim: 88100, corridas: 10, fotoFim: F }).ok);
ok('retorno sem foto é recusado; com foto, grava');
const comp = x => Object.assign({ data: '2026-11-16', moto: 'MOTO 03', entregador: 'Carlos Eduardo', turno: '08h-14h', kmIni: 90000, kmFim: 90080, corridas: 8 }, x);
assert.throws(() => exec('saveFullShift', comp()), /KM de retorno/);
assert(exec('saveFullShift', comp({ fotoFim: F })).ok);
ok('turno completo: exige só a foto do KM final');
env.db.sheets['Configurações'].rows.push(['Foto do KM obrigatória', 'Não']);
assert.strictEqual(exec('getApp').config.fotoObrigatoria, false);
assert(exec('openShift', saida({ moto: 'MOTO 05', kmIni: 99000 })).ok);
ok('com "Foto do KM obrigatória = Não" na aba Configurações, a foto vira opcional');
env.db.sheets['Configurações'].rows[env.db.sheets['Configurações'].rows.length - 1][1] = 'Sim';
assert.strictEqual(exec('getApp').config.fotoObrigatoria, true);
assert.strictEqual(exec('getApp').config.meta, 12);
ok('"Sim" volta a exigir; meta e revisão continuam lidas normalmente');
console.log('\nOK: foto obrigatória');
